"""Generate versions.lock.md from pins.env, requirements.lock and vulndb/snapshots.yaml.

versions.lock.md is a generated, human-readable view. `make doctor` regenerates it in
memory and fails if the committed file is out of date.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

from pipeline.common import REPO, load_pins, load_requirements
from pipeline.vulndb import load_snapshots

LOCK_DOC = REPO / "versions.lock.md"
GH = "https://github.com"


def _row(*cells: str) -> str:
    return "| " + " | ".join(cells) + " |"


def render() -> str:
    p = load_pins()
    reqs = load_requirements()
    snaps = load_snapshots()
    sdk = p["ZEPHYR_SDK_VERSION"]
    sdk_url = f"{GH}/zephyrproject-rtos/sdk-ng/releases/download/v{sdk}"
    digest = f"`{p['CI_BASE_DIGEST']}`" if p.get("CI_BASE_DIGEST") else "NOT RECORDED (run make pin-base)"
    out: list[str] = [
        "# versions.lock",
        "",
        "Generated by `make lock-doc` from `pins.env`, `requirements.lock` and",
        "`vulndb/snapshots.yaml`. Do not edit by hand; `make doctor` checks it is current.",
        "",
        "## Container images",
        "",
        _row("Role", "Image", "Tag", "Digest", "Digest recorded"),
        _row("---", "---", "---", "---", "---"),
        _row("build/tooling base", p["CI_BASE_IMAGE"], p["CI_BASE_TAG"], digest,
             p.get("CI_BASE_DIGEST_RECORDED") or "-"),
        _row("MQTT broker (make run)", p["MOSQUITTO_IMAGE"], p["MOSQUITTO_TAG"],
             f"`{p['MOSQUITTO_DIGEST']}`" if p.get("MOSQUITTO_DIGEST")
             else "NOT RECORDED (run make pin-mosquitto)",
             p.get("MOSQUITTO_DIGEST_RECORDED") or "-"),
        "",
        "## Zephyr and modules (west.yml)",
        "",
        _row("Project", "Version", "Commit"),
        _row("---", "---", "---"),
        _row("zephyr", p["ZEPHYR_VERSION"], f"`{p['ZEPHYR_COMMIT']}`"),
    ]
    west = yaml.safe_load((REPO / "west.yml").read_text(encoding="utf-8"))["manifest"]
    allow: list[str] = []
    for proj in west["projects"]:
        allow += list((proj.get("import") or {}).get("name-allowlist", []))
    by_key = {n.replace("-", "_").lower(): n for n in allow}
    for key in sorted(k for k in p if k.startswith("MODULE_") and k.endswith("_SHA")):
        name = key.removeprefix("MODULE_").removesuffix("_SHA").lower()
        name = by_key.get(name, name)
        out.append(_row(name, f"as pinned by zephyr {p['ZEPHYR_VERSION']}", f"`{p[key]}`"))
    out += [
        "",
        "## Toolchain and CLI tools (linux/amd64)",
        "",
        _row("Component", "Version", "Artifact", "sha256"),
        _row("---", "---", "---", "---"),
        _row("Zephyr SDK (minimal)", sdk,
             f"[zephyr-sdk-{sdk}_linux-x86_64_minimal.tar.xz]({sdk_url}/zephyr-sdk-{sdk}_linux-x86_64_minimal.tar.xz)",
             f"`{p['ZEPHYR_SDK_MINIMAL_SHA256']}`"),
        _row("Zephyr SDK arm-zephyr-eabi", sdk,
             f"[toolchain_gnu_linux-x86_64_arm-zephyr-eabi.tar.xz]({sdk_url}/toolchain_gnu_linux-x86_64_arm-zephyr-eabi.tar.xz)",
             f"`{p['ZEPHYR_SDK_ARM_SHA256']}`"),
    ]
    tools = [
        ("grype", "GRYPE", "anchore/grype", "v{v}", "grype_{v}_linux_amd64.tar.gz"),
        ("osv-scanner", "OSV_SCANNER", "google/osv-scanner", "v{v}", "osv-scanner_linux_amd64"),
        ("vexctl", "VEXCTL", "openvex/vexctl", "v{v}", "vexctl-linux-amd64"),
        ("cosign", "COSIGN", "sigstore/cosign", "v{v}", "cosign-linux-amd64"),
        ("jq", "JQ", "jqlang/jq", "jq-{v}", "jq-linux-amd64"),
    ]
    for label, key, repo, tag_fmt, asset_fmt in tools:
        v = p[f"{key}_VERSION"]
        tag, asset = tag_fmt.format(v=v), asset_fmt.format(v=v)
        out.append(_row(label, v, f"[{asset}]({GH}/{repo}/releases/download/{tag}/{asset})",
                        f"`{p[f'{key}_SHA256']}`"))
    out += [
        "",
        "## Python packages (requirements.lock, installed with --require-hashes)",
        "",
        _row("Package", "Version"),
        _row("---", "---"),
    ]
    out += [_row(name, ver) for name, ver in sorted(reqs.items())]
    out += [
        "",
        "## Vulnerability DB snapshots (vulndb/snapshots.yaml)",
        "",
        _row("Snapshot", "Source", "Built / Last-Modified", "Recorded", "sha256"),
        _row("---", "---", "---", "---", "---"),
    ]
    rows = 0
    for name, e in sorted(snaps["grype"].items()):
        out.append(_row(name, f"grype ({e['schema_version']})", str(e["built"]),
                        str(e["recorded_at"]), f"`{e['sha256']}`"))
        rows += 1
    for name, s in sorted(snaps["osv"].items()):
        for eco, e in sorted(s["ecosystems"].items()):
            lm = e.get("http_headers", {}).get("Last-Modified", "-")
            out.append(_row(name, f"osv {eco}", lm, str(s["recorded_at"]), f"`{e['sha256']}`"))
            rows += 1
    if rows == 0:
        out.append(_row("none recorded", "-", "-", "-", "-"))
    out += [
        "",
        "## How the pins were obtained",
        "",
        "- Zephyr commit: `git ls-remote` of the annotated tag (`refs/tags/<tag>^{}`).",
        "- Module SHAs: copied from zephyr's own `west.yml` at that commit.",
        "- SDK and CLI tool sha256: the project's published checksum file, cross-checked",
        "  against the GitHub release asset digest. The Docker build re-verifies every download.",
        "- Image digests: trust-on-first-use, recorded by `make pin-base` / `make pin-mosquitto`",
        "  on the date shown.",
        "- Python: `uv pip compile --generate-hashes` for CPython 3.12 / x86_64 Linux.",
        "- DB snapshots: trust-on-first-use, recorded by `make snapshot` on the date shown.",
        "",
    ]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 if versions.lock.md is stale")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        current = LOCK_DOC.read_text(encoding="utf-8") if LOCK_DOC.exists() else ""
        return 0 if current == text else 1
    Path(LOCK_DOC).write_text(text, encoding="utf-8")
    print(f"wrote {LOCK_DOC.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
